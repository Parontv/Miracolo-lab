import fs from 'node:fs';
import assert from 'node:assert/strict';
const seed=fs.readFileSync('bot-market-seed.js','utf8');
const router=fs.readFileSync('bot-live-router.js','utf8');
assert.equal((seed.match(/fetch\(/g)||[]).length,1,'Yahoo fallback must use one fetch');
const plan=router.match(/if\(u\.pathname==='\/api\/bot\/plan'\)return Response\.json\(await runAutoPaperBot\(env,\{execute:false\}\)\)/);
const run=router.match(/if\(u\.pathname==='\/api\/bot\/run'\).*?return Response\.json\(await runAutoPaperBot\(env\)\)/);
assert.ok(plan,'/api/bot/plan must route directly to KV-first Bot');
assert.ok(run,'/api/bot/run must route directly to KV-first Bot');
const beforeLive=router.split("if(u.pathname==='/api/live')")[0];
assert.equal((beforeLive.match(/aiWorker\.fetch/g)||[]).length,0,'Bot routes before /api/live must not call aiWorker.fetch');
assert.equal((router.match(/await refreshAlpacaEquities/g)||[]).length,2,'Alpaca market refresh is called only in cron and market-test');
assert.match(router,/name:'market',fetches:0/);
assert.match(router,/name:'crypto',fetches:3/);
assert.match(router,/name:'position',fetches:1/);
assert.match(router,/name:'decision',fetches:0/);
console.log('PASS bot subrequest contract');
